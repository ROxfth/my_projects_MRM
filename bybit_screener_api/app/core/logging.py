import logging


def setup_logging() -> None:
    """
    Настроить систему логирования приложения.

    Функция инициализирует базовую конфигурацию логирования
    с уровнем INFO и стандартным форматом сообщений,
    включающим время, уровень логирования, имя логгера
    и текст сообщения.

    Используется при старте приложения для централизованной
    настройки логирования.
    """
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s - %(levelname)s - %(name)s - %(message)s",
    )
